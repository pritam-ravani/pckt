// --------------------------------------------------------------- previews
// Home screens: the icon (Samsung-like squircle) at 48dp-equivalent and
// large, on light and dark wallpapers; Android 13 themed icons on both.
const prev = 'assets/branding/previews';
function homeScreen(name, page, iconOpts, label) {
  const big = 288, small = 144, tiny = 48; // tiny = 48 px (≈ 48dp at mdpi)
  const W = 40 + big + 40 + small + 40 + tiny + 40, H = big + 80;
  const items = [
    { img: render(big, iconOpts), size: big, x: 40, y: 40 },
    { img: render(small, iconOpts), size: small, x: 40 + big + 40, y: 40 + (big - small) / 2 },
    { img: render(tiny, iconOpts), size: tiny, x: 40 + big + 40 + small + 40, y: 40 + (big - tiny) / 2 },
  ];
  out(`${prev}/${name}.png`, png(W, H, compose(W, H, hex(page), items), true));
  void label;
}
