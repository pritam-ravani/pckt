// Run: node tool/gen_icons.js — generates lib/core/theme/icons.dart from the icons actually used in lib/.
// phosphor_flutter's Dart classes subclass IconData (final since Flutter 3.4x),
// so we keep only its bundled fonts and declare plain const IconData here.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..', 'lib');
const pkg = path.join(process.env.LOCALAPPDATA || '', 'Pub/Cache/hosted/pub.dev/phosphor_flutter-2.1.0/lib/src');
const out = path.join(root, 'core/theme/icons.dart');

const files = [];
(function walk(d) {
  for (const f of fs.readdirSync(d)) {
    const p = path.join(d, f);
    if (fs.statSync(p).isDirectory()) walk(p);
    else if (p.endsWith('.dart') && !p.endsWith('.g.dart') && path.resolve(p) !== path.resolve(out)) files.push(p);
  }
})(root);

// Duotone needs phosphor's two-layer widget; render those as Fill instead.
for (const f of files) {
  let s = fs.readFileSync(f, 'utf8');
  const before = s;
  s = s.replace(/PhosphorIconsDuotone\./g, 'PhosphorIconsFill.');
  if (s.includes('package:phosphor_flutter/phosphor_flutter.dart')) {
    const rel = path.relative(path.dirname(f), path.join(root, 'core/theme/icons.dart')).split(path.sep).join('/');
    s = s.replace("import 'package:phosphor_flutter/phosphor_flutter.dart';", `import '${rel.startsWith('.') ? rel : './' + rel}';`);
  }
  if (s !== before) fs.writeFileSync(f, s);
}

const used = { Fill: new Set(), Regular: new Set(), Bold: new Set() };
for (const f of files) {
  const s = fs.readFileSync(f, 'utf8');
  for (const m of s.matchAll(/PhosphorIcons(Fill|Regular|Bold)\.(\w+)/g)) used[m[1]].add(m[2]);
}

const fileFor = { Fill: 'phosphor_icons_fill.dart', Regular: 'phosphor_icons_regular.dart', Bold: 'phosphor_icons_bold.dart' };
let dart = `// GENERATED by tool/gen_icons.js — icons used by the app, backed by
// the fonts bundled with phosphor_flutter. Its own Dart classes extend
// IconData, which is final on current Flutter, so we don't import them.
import 'package:flutter/widgets.dart';

`;
for (const style of ['Fill', 'Regular', 'Bold']) {
  const src = fs.readFileSync(path.join(pkg, fileFor[style]), 'utf8');
  dart += `abstract final class PhosphorIcons${style} {\n`;
  for (const name of [...used[style]].sort()) {
    const m = new RegExp(`static const ${name} = PhosphorFlatIconData\\((0x[0-9a-f]+)`).exec(src);
    if (!m) { console.error('MISSING', style, name); process.exitCode = 1; continue; }
    dart += `  static const ${name} = IconData(${m[1]}, fontFamily: 'Phosphor${style}', fontPackage: 'phosphor_flutter');\n`;
  }
  dart += '}\n\n';
}
fs.writeFileSync(out, dart.trimEnd() + '\n');
console.log(Object.fromEntries(Object.entries(used).map(([k, v]) => [k, v.size])));
